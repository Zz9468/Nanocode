from __future__ import annotations
from typing import Any, Protocol, ContextManager
from Package.AgentMemory.Src.Application.Dto.MemoryRecord import MemoryRecord


class MemoryRepository(Protocol):
    def namespace(self, scope: str, identity: str) -> str: ...
    def list_records(self, namespaces: list[str], statuses: list[str] | None = None) -> list[MemoryRecord]: ...
    def commit(self, namespace: str, content: str, **attributes: Any) -> MemoryRecord: ...
    def enqueue(self, kind: str, payload: dict, job_key: str) -> str: ...
    def get(self, key: str, namespaces: list[str]) -> MemoryRecord | None: ...
    def capture(self, namespace: str, payload: dict) -> str: ...
    def claim(self, kinds: list[str] | None = None, namespaces: list[str] | None = None) -> dict | None: ...
    def finish(self, job: dict, error: str | None = None, result: dict | None = None) -> None: ...
    def job_counts(self, namespaces: list[str] | None = None) -> dict: ...
    def next_available_at(self, namespaces: list[str]) -> float | None: ...
    def consolidation_lock(self, namespace: str) -> ContextManager[bool]: ...
    def consolidation_result(self, namespace: str, signature: str, model_id: str) -> dict | None: ...
    def save_consolidation(self, namespace: str, signature: str, model_id: str, result: dict) -> None: ...
    def save_embedding(self, record: MemoryRecord, model_id: str, vector: list[float]) -> bool: ...
    def vectors(self, namespaces: list[str], model_id: str) -> dict: ...
    def mark_used(self, records: list[MemoryRecord]) -> None: ...


class ModelGateway(Protocol):
    identity: str
    def generate(self, system: str, payload: dict, schema: dict | None = None) -> dict: ...
    def embed(self, texts: list[str]) -> list[list[float]]: ...
    def rerank(self, query: str, documents: list[str], top_n: int) -> list[tuple[int, float]]: ...


class SourceReader(Protocol):
    def validate(self, workspace: str, paths: dict[str, str]) -> bool: ...
    def fingerprints(self, workspace: str, paths: list[str]) -> dict[str, str]: ...
    def spool(self, payload: dict) -> str: ...
    def replay(self) -> list[tuple[str, dict]]: ...
    def acknowledge(self, path: str) -> None: ...
    def export(self, destination: str, records: list[MemoryRecord]) -> dict: ...

class RequestBudget(Protocol):
    def reserve(self, kind: str, input_bound: int, output_bound: int = 0) -> str: ...
    def settle(self, key: str, usage: dict | None) -> None: ...
    def summary(self) -> dict: ...

